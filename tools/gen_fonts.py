#!/usr/bin/env python3
"""Generate the bitmap font tables used by the port's GDI emulation.

Added 2026-10-12 for the Stellar Frontier Godot port.

Windows 98/2000/XP drew this game's text with Arial, "Small Fonts",
Courier New, Lucida Console and the MS Sans Serif / Tahoma UI font, without
anti-aliasing.  Those fonts are Microsoft's and are not redistributable, so
the port uses the metric-compatible Liberation fonts (SIL Open Font License)
rendered the same way GDI rendered TrueType fonts at small sizes:

  * cell height (CreateFont with a positive height) = round(winAscent*s) +
    round(winDescent*s), using the largest integer pixels-per-em that fits;
  * a non-zero CreateFont width scales the font horizontally so that the
    average character width (OS/2 xAvgCharWidth of the *Microsoft* font)
    equals the requested width;
  * hinted, 1-bit (non-anti-aliased) glyphs, Windows-1252 character set.

Output: src/w32emu/sf_fonts.inc (C++ data, included by w32_gdi_text.cpp).
Usage:  python3 tools/gen_fonts.py
"""
import os
import sys
import freetype

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = '/usr/share/fonts/truetype/liberation/'

# family id -> (regular file, bold file, MS xAvgCharWidth regular, bold,
#               winAscent, winDescent, pitch&family byte)
FAMILIES = {
    'sans': ('LiberationSans-Regular.ttf', 'LiberationSans-Bold.ttf',
             904, 983, 1854, 434, 0x22),       # Arial: VARIABLE_PITCH|FF_SWISS
    'mono': ('LiberationMono-Regular.ttf', 'LiberationMono-Bold.ttf',
             1229, 1229, 1705, 615, 0x31),     # Courier New: FIXED|FF_MODERN
}

# (family, cell height, requested width (0 = natural), weight)
WANT = []
for h in range(8, 25):
    WANT.append(('sans', h, 0, 400))
    WANT.append(('sans', h, 0, 700))
for h in range(9, 21):
    WANT.append(('mono', h, 0, 400))
    WANT.append(('mono', h, 0, 700))
WANT += [
    ('sans', 14, 5, 400),    # S_FONT_HELV/ARIAL 8 -> CreateFont(14,5): controls, chat, radar
    ('sans', 14, 5, 700),
    ('sans', 12, 4, 400),    # "Small Fonts" 7 -> CreateFont(12,4)
    ('mono', 11, 8, 400),    # "Lucida Console" 8x11 (video console, NT)
    ('mono', 15, 8, 400),    # "Courier New" 8x15 (video console, 9x)
    ('mono', 14, 5, 400),    # S_FONT_COURIER 8
]

CP1252 = [None] * 256
for i in range(256):
    try:
        CP1252[i] = bytes([i]).decode('cp1252')
    except UnicodeDecodeError:
        CP1252[i] = None


def metrics_for(fam, height):
    """Largest integer ppem whose GDI cell height fits in 'height'."""
    _, _, _, _, asc, desc, _ = FAMILIES[fam]
    best = None
    for ppem in range(3, 80):
        a = int(asc * ppem / 2048 + 0.5)
        d = int(desc * ppem / 2048 + 0.5)
        if a + d <= height:
            best = (ppem, a, d)
    return best


def render(fam, height, width, weight):
    reg, bold, avg_r, avg_b, asc, desc, pf = FAMILIES[fam]
    ppem, a, d = metrics_for(fam, height)
    avg_ms = avg_b if weight >= 600 else avg_r
    natural = int(avg_ms * ppem / 2048 + 0.5)
    xscale = 1.0
    if width and natural:
        xscale = width / float(avg_ms * ppem / 2048)
    face = freetype.Face(LIB + (bold if weight >= 600 else reg))
    face.set_char_size(int(round(ppem * xscale * 64)), ppem * 64, 72, 72)
    glyphs = []
    bits = bytearray()
    maxw = 0
    for code in range(256):
        ch = CP1252[code]
        if code < 32 or ch is None:
            glyphs.append((0, 0, 0, 0, 0, 0))
            continue
        face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_MONO)
        g = face.glyph
        bm = g.bitmap
        adv = (g.advance.x + 32) >> 6
        maxw = max(maxw, adv)
        off = len(bits)
        rowbytes = (bm.width + 7) // 8
        buf = bm.buffer
        for r in range(bm.rows):
            row = buf[r * bm.pitch: r * bm.pitch + rowbytes]
            bits.extend(bytes(row))
        glyphs.append((adv, g.bitmap_left, g.bitmap_top, bm.width, bm.rows, off))
    avgw = width if width else natural
    return dict(fam=fam, height=a + d, req_height=height, width=width,
                weight=weight, ascent=a, descent=d, ppem=ppem,
                intlead=(a + d) - ppem, avgw=avgw, maxw=maxw, pf=pf,
                glyphs=glyphs, bits=bits)


def main():
    out = []
    out.append('/* sf_fonts.inc -- generated by tools/gen_fonts.py (port, 2026-10-12).')
    out.append('   Glyphs rendered from the Liberation fonts (SIL Open Font License 1.1,')
    out.append('   see third_party/liberation/LICENSE). Do not edit. */')
    fonts = []
    for i, (fam, h, w, wt) in enumerate(WANT):
        f = render(fam, h, w, wt)
        fonts.append(f)
        out.append('static const SfGlyph sf_font%d_glyphs[256] = {' % i)
        for (adv, x, y, gw, gh, off) in f['glyphs']:
            out.append('  {%d,%d,%d,%d,%d,%d},' % (adv, x, y, gw, gh, off))
        out.append('};')
        b = f['bits']
        out.append('static const unsigned char sf_font%d_bits[%d] = {' % (i, max(1, len(b))))
        for k in range(0, max(1, len(b)), 24):
            out.append('  ' + ','.join(str(x) for x in b[k:k + 24]) + ',')
        out.append('};')
    out.append('static const SfFontData sf_fonts[] = {')
    for i, f in enumerate(fonts):
        out.append('  {"%s",%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,0x%02x,sf_font%d_glyphs,sf_font%d_bits},' % (
            f['fam'], f['req_height'], f['width'], f['weight'], f['height'],
            f['ascent'], f['descent'], f['intlead'], f['avgw'], f['maxw'],
            f['ppem'], f['pf'], i, i))
    out.append('};')
    out.append('static const int sf_num_fonts = %d;' % len(fonts))
    path = os.path.join(ROOT, 'src', 'w32emu', 'sf_fonts.inc')
    with open(path, 'w') as fp:
        fp.write('\n'.join(out) + '\n')
    print('wrote', path, len(fonts), 'fonts')


if __name__ == '__main__':
    main()
